let LANG = "en";
function t(key, ...a) {
  let s = (STR[LANG] && STR[LANG][key]) || STR.en[key] || key;
  a.forEach((v, i) => { s = s.split("{" + i + "}").join(v); });
  return s;
}
async function initLang() {
  let l = null;
  try { l = (await browser.storage.local.get("lang")).lang; } catch (e) {}
  if (!l) { try { l = (browser.i18n.getUILanguage() || "en").toLowerCase().startsWith("fr") ? "fr" : "en"; } catch (e) { l = "en"; } }
  LANG = STR[l] ? l : "en";
}
// Textes statiques de la page : data-i18n (texte), data-i18n-html (balisage maison), data-i18n-ph, data-i18n-title
function applyI18n(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach(e => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach(e => { e.innerHTML = t(e.dataset.i18nHtml); });   // chaînes du dictionnaire uniquement
  root.querySelectorAll("[data-i18n-ph]").forEach(e => { e.placeholder = t(e.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach(e => { e.title = t(e.dataset.i18nTitle); });
}
function bindLang(select, onChange) {
  select.value = LANG;
  select.onchange = async () => {
    LANG = select.value;
    try { await browser.storage.local.set({ lang: LANG }); } catch (e) {}
    applyI18n(); if (onChange) onChange();
  };
}
